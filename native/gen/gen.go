// Package gen generates the Go types that native methods use for the
// structures, tables and enums of their signatures. The generated code
// holds only types; the VM converts values by the rt tags of the fields.
package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strings"

	"github.com/tim-riep/go-runtime/lang/types"
)

// Generate returns the Go source of the types used by the native methods
// of a checked program, in package goPkg.
func Generate(prog *types.Program, goPkg string) ([]byte, error) {
	g := &generator{structs: map[string]*types.Struct{}, enums: map[string]*types.Enum{}}
	for _, k := range prog.Classes {
		for _, m := range k.Methods {
			if !m.Native {
				continue
			}
			for _, p := range m.Sig.Params {
				g.collect(p)
			}
			g.collect(m.Sig.Result)
		}
	}
	var b bytes.Buffer
	b.WriteString(License)
	fmt.Fprintf(&b, "// Code generated by rt gen natives from package %s. DO NOT EDIT.\n\n", prog.Package)
	fmt.Fprintf(&b, "package %s\n\n", goPkg)
	var body bytes.Buffer
	for _, name := range sortedKeys(g.enums) {
		e := g.enums[name]
		goName := GoName(name)
		base := "string"
		if e.Base.Kind != types.String {
			base = "int64"
		}
		fmt.Fprintf(&body, "// %s is the enum %s.\ntype %s %s\n\n", goName, name, goName, base)
		fmt.Fprintf(&body, "// Fixed values of %s.\nconst (\n", name)
		for _, v := range e.Values {
			val := fmt.Sprintf("%q", v.Value)
			if base != "string" {
				val = v.Value
			}
			fmt.Fprintf(&body, "\t%s%s %s = %s\n", goName, camel(v.Name), goName, val)
		}
		body.WriteString(")\n\n")
	}
	for _, name := range sortedKeys(g.structs) {
		s := g.structs[name]
		what := "structure"
		if s.Table {
			what = "table"
		}
		fmt.Fprintf(&body, "// %s is the %s %s.\ntype %s struct {\n", GoName(name), what, name, GoName(name))
		for _, f := range s.Fields {
			fmt.Fprintf(&body, "\t%s %s `rt:%q`\n", FieldName(f.Name), g.goType(f.Type), f.Name)
		}
		body.WriteString("}\n\n")
	}
	var imports []string
	for _, imp := range []string{"time", "github.com/tim-riep/go-runtime/lang/dec", "github.com/tim-riep/go-runtime/model", "github.com/tim-riep/go-runtime/native"} {
		short := imp[strings.LastIndex(imp, "/")+1:]
		if bytes.Contains(body.Bytes(), []byte(short+".")) {
			imports = append(imports, fmt.Sprintf("%q", imp))
		}
	}
	if len(imports) > 0 {
		fmt.Fprintf(&b, "import (\n%s\n)\n\n", strings.Join(imports, "\n"))
	}
	b.Write(body.Bytes())
	return format.Source(b.Bytes())
}

