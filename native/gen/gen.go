type generator struct {
	structs map[string]*types.Struct
	enums   map[string]*types.Enum
}

func (g *generator) collect(t types.Type) {
	switch x := types.NonOpt(t).(type) {
	case *types.Struct:
		if _, seen := g.structs[x.Name]; seen {
			return
		}
		g.structs[x.Name] = x
		for _, f := range x.Fields {
			g.collect(f.Type)
		}
	case *types.Enum:
		g.enums[x.Name] = x
	case *types.Array:
		g.collect(x.Elem)
	}
}

func (g *generator) goType(t types.Type) string {
	if o, ok := t.(*types.Optional); ok {
		return "model.Optional[" + g.goType(o.Elem) + "]"
	}
	switch x := t.(type) {
	case *types.Struct:
		return GoName(x.Name)
	case *types.Enum:
		return GoName(x.Name)
	case *types.Array:
		return "[]" + g.goType(x.Elem)
	}
	b := types.BasicOf(t)
	if b == nil {
		return "any"
	}
	return map[types.BasicKind]string{types.String: "string", types.Int4: "int32", types.Int8: "int64", types.Dec: "dec.Dec",
		types.Date: "native.Date", types.Timestamp: "time.Time", types.Bool: "bool", types.UUID: "native.UUID", types.Bytes: "[]byte"}[b.Kind]
}

// GoName returns the Go name of a structure, table or enum: its name
// without namespace in camel case, /TRTEST/ITEM_INFO is ItemInfo.
func GoName(name string) string {
	return camel(name[strings.LastIndex(name, "/")+1:])
}

// FieldName returns the Go name of a field: NOTE is Note, and an
// extension field keeps its package, /TROTTO/OTTO_ID is TrottoOttoID.
func FieldName(name string) string {
	return camel(strings.ReplaceAll(strings.Trim(name, "/"), "/", "_"))
}

func camel(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part == "" {
			continue
		}
		if part == "ID" || part == "UUID" || part == "URL" || part == "HTML" || part == "XML" {
			b.WriteString(part)
			continue
		}
		b.WriteString(part[:1] + strings.ToLower(part[1:]))
	}
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
